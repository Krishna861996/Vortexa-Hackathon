create table if not exists public.challenges (
    id text primary key,
    title text not null,
    description text not null,
    difficulty text not null check (difficulty in ('beginner', 'easy', 'medium', 'hard', 'advanced')),
    function_name text not null,
    starter_code text not null,
    visible_tests jsonb not null check (jsonb_typeof(visible_tests) = 'array'),
    hints jsonb not null check (jsonb_typeof(hints) = 'array'),
    concept_tags text[] not null default '{}',
    sort_order integer not null unique
);

create table if not exists public.challenge_hidden_tests (
    challenge_id text primary key references public.challenges(id) on delete cascade,
    tests jsonb not null check (jsonb_typeof(tests) = 'array')
);

create table if not exists public.learners (
    id text primary key,
    hint_positions jsonb not null default '{}'::jsonb
        check (jsonb_typeof(hint_positions) = 'object')
);

create table if not exists public.attempts (
    id bigint generated by default as identity primary key,
    challenge_id text not null references public.challenges(id),
    learner_id text not null references public.learners(id),
    submitted_code text not null,
    test_results jsonb not null check (jsonb_typeof(test_results) = 'array'),
    passed boolean not null,
    concepts_practiced text[] not null default '{}',
    submitted_at timestamptz not null default now()
);

create index if not exists attempts_learner_time_idx
    on public.attempts (learner_id, submitted_at desc);

alter table public.challenges enable row level security;
alter table public.challenge_hidden_tests enable row level security;
alter table public.learners enable row level security;
alter table public.attempts enable row level security;

