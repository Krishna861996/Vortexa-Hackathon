"""Generate the rerunnable SQL seed from the server's canonical question bank."""
import json
from pathlib import Path
from app.local_repository import CHALLENGES, HIDDEN_TESTS

original = {key: index + 1 for index, key in enumerate([
    "add-numbers", "is-even", "reverse-text", "count-vowels", "fizz-buzz", "sum-list",
])}
rows = []
for item in CHALLENGES:
    if item["id"] not in original:
        original[item["id"]] = len(original) + 1
    rows.append({**item, "sort_order": original[item["id"]]})
payload = json.dumps(rows, ensure_ascii=False).replace("'", "''")
private = json.dumps([{"challenge_id": key, "tests": tests} for key, tests in HIDDEN_TESTS.items()]).replace("'", "''")
sql = f"""-- Generated by backend/export_catalog.py. Preserves attempts and learners.
begin;
insert into public.challenges
select * from jsonb_populate_recordset(null::public.challenges, '{payload}'::jsonb)
on conflict (id) do update set
 title = excluded.title, description = excluded.description, difficulty = excluded.difficulty,
 function_name = excluded.function_name, starter_code = excluded.starter_code,
 visible_tests = excluded.visible_tests, hints = excluded.hints,
 concept_tags = excluded.concept_tags, sort_order = excluded.sort_order;
insert into public.challenge_hidden_tests
select * from jsonb_populate_recordset(null::public.challenge_hidden_tests, '{private}'::jsonb)
on conflict (challenge_id) do update set tests = excluded.tests;
commit;
"""
Path(__file__).resolve().parent.parent.joinpath("supabase", "catalog.sql").write_text(sql, encoding="utf-8")
print(f"Exported {len(rows)} challenges.")
